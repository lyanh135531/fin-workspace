CREATE TABLE "USER_REMINDER_SETTING" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "user_id" UUID NOT NULL,
    "noon_enabled" BOOLEAN NOT NULL DEFAULT true,
    "evening_enabled" BOOLEAN NOT NULL DEFAULT true,
    "time_zone" VARCHAR(64) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    "last_noon_sent_date" VARCHAR(10),
    "last_evening_sent_date" VARCHAR(10),
    "last_bill_alert_sent_date" VARCHAR(10),
    "dismissed_date" VARCHAR(10),
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "USER_REMINDER_SETTING_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "USER_PUSH_SUBSCRIPTION" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "user_id" UUID NOT NULL,
    "endpoint" TEXT NOT NULL,
    "p256dh" VARCHAR(255) NOT NULL,
    "auth" VARCHAR(255) NOT NULL,
    "user_agent" VARCHAR(512),
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "USER_PUSH_SUBSCRIPTION_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "WEB_PUSH_VAPID_KEY" (
    "id" VARCHAR(32) NOT NULL DEFAULT 'default',
    "public_key" VARCHAR(255) NOT NULL,
    "private_key_jwk" JSONB NOT NULL,
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "WEB_PUSH_VAPID_KEY_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "USER_REMINDER_SETTING_user_id_key" ON "USER_REMINDER_SETTING"("user_id");
CREATE UNIQUE INDEX "USER_PUSH_SUBSCRIPTION_endpoint_key" ON "USER_PUSH_SUBSCRIPTION"("endpoint");
CREATE INDEX "USER_PUSH_SUBSCRIPTION_user_id_idx" ON "USER_PUSH_SUBSCRIPTION"("user_id");

ALTER TABLE "USER_REMINDER_SETTING" ADD CONSTRAINT "USER_REMINDER_SETTING_user_id_fkey"
FOREIGN KEY ("user_id") REFERENCES "USERS"("id") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "USER_PUSH_SUBSCRIPTION" ADD CONSTRAINT "USER_PUSH_SUBSCRIPTION_user_id_fkey"
FOREIGN KEY ("user_id") REFERENCES "USERS"("id") ON DELETE CASCADE ON UPDATE CASCADE;
